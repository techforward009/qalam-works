import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";

describe("Khateeb proper public Book Library entry", () => {
  const home = readFileSync("app/tools/khateeb-studio/KhateebStudioContent.tsx", "utf8");
  const route = readFileSync("app/api/khateeb/book-reader/route.ts", "utf8");
  const reader = readFileSync("app/tools/khateeb-studio/BookReader.tsx", "utf8");
  const page = readFileSync("app/tools/khateeb-studio/library/BookLibraryPageClient.tsx", "utf8");
  it("links a direct dedicated book shelf before the topic search", () => {
    expect(home).toContain('href="/tools/khateeb-studio/library"');
    expect(home).toContain("کتاب خانہ — مکمل کتابیں پڑھیں");
    expect(home.indexOf('href="/tools/khateeb-studio/library"')).toBeLessThan(home.indexOf("مجلس کا موضوع تلاش کریں"));
    expect(page).toContain("<BookReader");
  });
  it("keeps exact R2-only source and the old Blob route out of the public reader", () => {
    expect(route).toContain("readBookRecordFromR2");
    expect(route).toContain("readBookSourceFromR2");
    expect(route).toContain("bookLibraryR2IsSelected");
    expect(route).not.toContain("researchBlobClientFromEnv");
    expect(reader).toContain("/api/khateeb/book-reader");
    expect(reader).not.toContain("/api/research/book-reader");
    expect(reader).toContain("paginateMeasuredFlow");
    expect(reader).toContain("document.fonts.ready");
    expect(reader).toContain("readingMode");
  });
  it("keeps a book-shaped sheet, Quran-style top-center page turner, and source-correct book fonts", () => {
    const css = readFileSync("app/tools/khateeb-studio/BookReader.module.css", "utf8");
    const client = readFileSync("app/tools/khateeb-studio/library/BookLibraryPageClient.tsx", "utf8");
    expect(css).toContain("aspect-ratio: 148 / 210");
    expect(css).toContain("width: min(100%, 43rem)");
    expect(css).toContain('grid-template-areas: "chapter navigation book"');
    expect(reader).toContain('<nav className={styles.pageNavigation}');
    expect(reader).toContain('className={styles.pageArrowIcon}');
    expect(reader).toContain('className={styles.pageNumberMain}');
    expect(reader).toContain("bookReaderRunningHeading(reading, locale)");
    expect(reader).not.toContain("کتاب کا حصہ ");
    expect(reader).toContain("onClick={ur ? nextPart : previousPart}");
    expect(reader).toContain("onClick={ur ? previousPart : nextPart}");
    expect(reader).toContain("ref={moreMenuRef}");
    expect(reader).toContain('document.addEventListener("pointerdown", closeOutsideMenu)');
    expect(css).toContain('.readerShell:lang(ur) .toolbar option');
    expect(reader).not.toContain('" از " + visualPages.length');
    const sharedCss = readFileSync("app/globals.css", "utf8");
    expect(sharedCss).toContain('font-family: "Noorehuda", "Digital Khatt IndoPak Book", serif !important');
    expect(reader).toContain('text.classList.add("qalam-book-arabic")');
    expect(css).not.toMatch(/font-family:.*(?:Digital Khatt|Traditional Arabic)/);
    expect(css).toContain('font-family: "Nafees Nastaleeq", "Mehr Nastaliq Web"');
    expect(sharedCss).toContain("font-size: 1.25em");
    expect(sharedCss).toContain(".qalam-book-arabic .qalam-book-arabic");
    expect(reader).not.toContain("<footer className={styles.pageFooter}>");
    expect(reader).not.toContain("نسخے کی معلومات");
    expect(reader).not.toContain('aria-label={ur ? "مطالعے کی صورت" : "Reading mode"}');
    expect(reader).not.toContain("changeReadingMode");
    expect(css).toContain(".chapterTitle { grid-area: chapter; min-width: 0; text-align: left;");
    expect(css).toContain(".bookIdentity { grid-area: book; min-width: 0; text-align: right;");
    expect(css).toContain("min-width: max-content;");
    expect(css).toContain("gap: .18rem;");
    expect(client).toContain("max-w-[58rem]");
  });
  it("keeps bookmarks, page controls and source paragraphs separate from translation", () => {
    const css = readFileSync("app/tools/khateeb-studio/BookReader.module.css", "utf8");
    expect(reader).toContain("KHATEEB_READER_PROGRESS_KEY");
    expect(reader).toContain("qalam-book-reader-print");
    expect(reader).toContain("readingFlowUnits");
    expect(reader).toContain("displayArabicBookText(fragment.text)");
    expect(reader).toContain("splitArabicBookParentheses(displayArabicBookText(fragment.text))");
    expect(reader).toContain('document.createElement("bdi")');
    const passage = readFileSync("app/tools/khateeb-studio/BookPassageText.tsx", "utf8");
    expect(passage).toContain('dir="rtl" className="khateeb-book-bracket-isolate"');
    expect(css).toContain("unicode-bidi: isolate;");

    expect(reader).toContain('onCopyCapture={copySourceSelection}');
    expect(reader).toContain("bookArabicDisplay={fragment.language === \"ar\"}");
    expect(reader).not.toContain('{ur ? "صفحہ " : "Page "}');
    expect(reader).toContain("data-book-language={reading.language}");
    expect(css).toContain('.readingPage[data-book-language="en"] .paragraphs { gap: .55rem; }');
    expect(css).toContain("font-size: .84em; line-height: 1.62;");
    expect(css).toContain("border: 0;");
    expect(css).not.toContain("border-radius: 50%;");
    expect(reader).toContain('useState<"digital" | "balagh-layout">("digital")');
    expect(reader).toContain('data-arabic-page-style={reading.language === "ar" ? arabicPageStyle : undefined}');
    expect(reader).toContain("fontSize, arabicPageStyle, layoutSize");
    expect(reader).toContain('selectedSource?.language === "ar"');
    expect(css).toContain('width: min(100%, 546px)');
    expect(css).not.toContain('font-size: 30px !important;');
    expect(css).toContain('line-height: 56px !important;');
    expect(css).not.toContain('font-family: "Traditional Arabic", var(--font-amiri)');
    expect(css).not.toContain("font-family: noor1");

    expect(reader).toContain("اصل");
  });
});
