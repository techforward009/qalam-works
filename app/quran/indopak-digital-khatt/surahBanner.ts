export function surahBanner(surah: number): {
  place: string;
  surahNumber: string;
  name: string;
  revealed: string;
  ayatCount: string;
} {
  const name = BANNER_NAMES[surah - 1] ?? "";
  const count = HAFS_AYAH_COUNTS[surah - 1] ?? 0;
  const revealed = REVELATION_ORDER[surah - 1] ?? 0;
  return {
    place: MADANI.has(surah) ? "مَدَنِيَّةٌ" : "مَكِّيَّةٌ",
    surahNumber: easternDigits(surah),
    name: `سُوْرَةُ ${name}`,
    revealed: easternDigits(revealed),
    ayatCount: easternDigits(count),
  };
}
